// Ramp order: higher bins must be more prominent (further from the card) in each theme.
function rampCheck(theme) {
  const t = THEMES[theme];
  const r = [1, 2, 3, 4, 5].map((i) => ratio(t[`seq-${i}`], t.card));
  return { ok: r.every((v, i) => i === 0 || v > r[i - 1]), ratios: r.map((v) => v.toFixed(2)) };
}

const rows = [];
let fails = 0;
for (const theme of ['light', 'dark']) {
  const t = THEMES[theme];
  for (const [fg, bg, min, what] of pairs) {
    const r = ratio(t[fg], t[bg]);
    const pass = r >= min;
    if (!pass) fails++;
    rows.push({ theme, fg, bg, fgv: t[fg], bgv: t[bg], ratio: r, min, pass, what });
  }
}

const lines = [];
lines.push('# Contrast report (generated by scripts/check-contrast.mjs)', '');
lines.push('| Theme | Foreground | Background | Ratio | Needs | Result | Use |', '|---|---|---|---:|---:|---|---|');
for (const r of rows) {
  lines.push(`| ${r.theme} | --${r.fg} ${r.fgv} | --${r.bg} ${r.bgv} | ${r.ratio.toFixed(2)} | ${r.min}:1 | ${r.pass ? 'PASS' : '**FAIL**'} | ${r.what} |`);
}
lines.push('');
for (const theme of ['light', 'dark']) {
  const rc = rampCheck(theme);
  if (!rc.ok) fails++;
  lines.push(`- Sequential ramp (${theme}): contrast vs card by bin ${rc.ratios.join(' < ')} -> ${rc.ok ? 'PASS (monotonic, lowest >= 3:1)' : '**FAIL** (not monotonic)'}`);
}
lines.push('', `**${rows.length} pairs checked, ${fails} failure(s).**`);

const report = lines.join('\n');
console.log(report);
mkdirSync(join(ROOT, 'screenshots'), { recursive: true });
writeFileSync(join(ROOT, 'screenshots', 'contrast-report.md'), report + '\n');
if (fails) process.exit(1);
